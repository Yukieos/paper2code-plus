class CodeWriterAgent:
    def __init__(self, config: CodeWriterConfig):
        self.config = config
        self.llm = ChatOpenAI(model=config.model_name, temperature=config.temperature)
        
        # Code generation chain
        prompt = ChatPromptTemplate.from_template(CODE_PROMPT)
        self.chain = prompt | self.llm | StrOutputParser()
        
        # Code review chain with structured outputs (CodeReviewResult)
        review_llm = ChatOpenAI(
            model=config.model_name,
            temperature=0.0,
        ).with_structured_output(CodeReviewResult, method="function_calling")
        review_prompt = ChatPromptTemplate.from_template(CODE_REVIEW_PROMPT)
        self.review_chain = review_prompt | review_llm
        
        # Code revision chain
        revise_prompt = ChatPromptTemplate.from_template(CODE_REVISE_PROMPT)
        self.revise_chain = revise_prompt | self.llm | StrOutputParser()

    def run(self, state: CodegenState) -> CodegenState:
        plan = state.get("plan")
        if not plan:
            raise ValueError("CodeWriterAgent requires 'plan' in state.")

        ups_ir = state.get("ups_ir", {})
        ups_ir_summary = summarize_ups_ir(ups_ir, max_chars=3000)
        config_template = state.get("config_template", {})
        flow_reasoning = json.dumps(state.get("flow_reasoning", {}), ensure_ascii=False, indent=2)
        parameter_placeholders = json.dumps(state.get("parameter_placeholders", []), ensure_ascii=False, indent=2)
        
        file_specs = plan.get("files", [])
        generated: List[str] = []
        reviews: Dict[str, str] = {}
        drafts: Dict[str, List[str]] = {}

        if self.config.limit_files is not None:
            file_specs = file_specs[: self.config.limit_files]

        for spec in file_specs:
            file_path = spec.get("path")
            if not file_path:
                continue

            absolute_path = self.config.output_dir / file_path
            absolute_path.parent.mkdir(parents=True, exist_ok=True)
            
            drafts[file_path] = []
            
            logger.info("Generating %s", absolute_path)

            # First draft
            file_plan_json = json.dumps(spec, ensure_ascii=False, indent=2)
            prompt_input = {
                "file_path": file_path,
                "file_plan": file_plan_json,
                "config_template": json.dumps(config_template, indent=2),
                "parameter_placeholders": parameter_placeholders,
                "ups_ir_summary": ups_ir_summary,
                "flow_reasoning": flow_reasoning,
            }
            
            # Generate code with retry on failure
            max_code_attempts = 2
            first_draft = None
            
            for code_attempt in range(max_code_attempts):
                try:
                    raw = self.chain.invoke(prompt_input)
                    first_draft = strip_fences(raw)
                    
                    # Validate it's actual code (not an error message)
                    if first_draft and len(first_draft) > 50 and (
                        "def " in first_draft or "class " in first_draft or "import " in first_draft
                    ):
                        break
                    elif code_attempt < max_code_attempts - 1:
                        logger.warning(f"Code generation attempt {code_attempt + 1} produced non-code output")
                        prompt_input["file_plan"] = f"IMPORTANT: Generate actual Python code, not explanations.\n\n{prompt_input['file_plan']}"
                except Exception as e:
                    logger.error(f"Code generation attempt {code_attempt + 1} failed: {e}")
                    if code_attempt == max_code_attempts - 1:
                        # Fallback to minimal implementation
                        first_draft = f"""# Auto-generated fallback for {file_path}
                        # Generation failed - manual implementation required

                        import logging

                        logger = logging.getLogger(__name__)

                        def main():
                            logger.warning("This is a fallback implementation. Please implement the actual logic.")
                            pass

                        if __name__ == "__main__":
                            main()
                        """
            
            if not first_draft:
                first_draft = "# Failed to generate code\npass"
            
            # Save intermediate draft
            if self.config.save_intermediate:
                draft_path = self.config.intermediate_dir / f"{file_path.replace('/', '_')}.v1.py"
                draft_path.write_text(first_draft, encoding="utf-8")
                drafts[file_path].append(str(draft_path))
            
            # Review the code
            review_input = {
                "code": first_draft,
                "file_spec": file_plan_json,
                "acceptance_criteria": json.dumps(spec.get("acceptance_criteria", []))
            }
            # Review with error handling
            try:
                review_model: CodeReviewResult = self.review_chain.invoke(review_input)
                review = review_model.model_dump()
                reviews[file_path] = json.dumps(review, indent=2)
            except Exception as e:
                logger.warning(f"Code review failed for {file_path}: {e}")
                review = {"issues": [], "severity": "low", "suggestions": []}
                reviews[file_path] = json.dumps(review, indent=2)
            
            # Check if revision needed
            if review.get("issues"):
                logger.info(f"Revising {file_path} based on {len(review['issues'])} issues")
                
                # Revise based on review
                try:
                    revise_input = {
                        "original_code": first_draft,
                        "review": json.dumps(review, indent=2),
                        "file_spec": file_plan_json
                    }
                    revised_raw = self.revise_chain.invoke(revise_input)
                    final_code = strip_fences(revised_raw)
                    
                    # Validate revised code
                    if not final_code or len(final_code) < len(first_draft) * 0.5:
                        logger.warning(f"Revision produced shorter code for {file_path}, keeping original")
                        final_code = first_draft
                except Exception as e:
                    logger.error(f"Code revision failed for {file_path}: {e}. Using original.")
                    final_code = first_draft
                
                # Save revised draft
                if self.config.save_intermediate:
                    draft_path = self.config.intermediate_dir / f"{file_path.replace('/', '_')}.v2.py"
                    draft_path.write_text(final_code, encoding="utf-8")
                    drafts[file_path].append(str(draft_path))
            else:
                final_code = first_draft
            
            # Write final version
            absolute_path.write_text(final_code, encoding="utf-8")
            generated.append(str(absolute_path))

        state["generated_files"] = generated
        state["code_reviews"] = reviews
        state["intermediate_drafts"] = drafts
        
        logger.info("CodeWriterAgent wrote %d files into %s", len(generated), self.config.output_dir)
        return state


_MAIN_BLOCK_RE = re.compile(r'^(?P<indent>[ \t]*)if\s+__name__\s*==\s*[\'"]__main__[\'"]\s*:\s*$')


def _fix_empty_main_block(path: Path) -> bool:
    """Insert `pass` into an `if __name__ == "__main__":` block whose body is
    only comments/blank lines.

    The code-writing agents occasionally fill that block entirely with
    commented-out "example usage" and no real statement — valid-looking but
    actually a SyntaxError (an indented block needs at least one statement).
    Fixed deterministically here rather than relying on the LLM to always
    follow a "don't do this" prompt instruction. Returns True if applied.
    """
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()

    for i, line in enumerate(lines):
        match = _MAIN_BLOCK_RE.match(line)
        if not match:
            continue

        base_indent = match.group("indent")
        body_indent = None
        has_real_statement = False
        j = i + 1
        while j < len(lines):
            stripped = lines[j].strip()
            if not stripped:
                j += 1
                continue
            line_indent = lines[j][: len(lines[j]) - len(lines[j].lstrip())]
            if len(line_indent) <= len(base_indent):
                break
            if body_indent is None:
                body_indent = line_indent
            if not stripped.startswith("#"):
                has_real_statement = True
            j += 1

        if not has_real_statement:
            lines.insert(i + 1, f"{body_indent or base_indent + '    '}pass")
            path.write_text("\n".join(lines) + "\n", encoding="utf-8")
            return True

    return False


class SyntaxCheckerAgent:
    """Lightweight syntax checking - only basic Python syntax validation."""

    def __init__(self, output_dir: Path):
        self.output_dir = output_dir

    def run(self, state: CodegenState) -> CodegenState:
        """Check syntax of all generated files."""
        generated_files = state.get("generated_files", [])
        results = {}
        syntax_errors = []

        for file_path in generated_files:
            path = Path(file_path)
            if not path.exists() or path.suffix != ".py":
                continue

            if _fix_empty_main_block(path):
                logger.info(f"SyntaxCheckerAgent auto-fixed an empty __main__ block in {path.name}")

            error = self._check_syntax(path)
            if error:
                results[str(path)] = {"passed": False, "error": error}
                syntax_errors.append(f"{path.name}: {error}")
            else:
                results[str(path)] = {"passed": True, "error": None}

        state["static_check_results"] = results

        # Save results
        results_path = Path("output") / "syntax_check_results.json"
        with open(results_path, "w", encoding="utf-8") as fp:
            json.dump(results, fp, ensure_ascii=False, indent=2)

        if syntax_errors:
            logger.warning(f"SyntaxCheckerAgent found {len(syntax_errors)} syntax errors")
            state["syntax_errors"] = syntax_errors

        return state

    @staticmethod
    def _check_syntax(file_path: Path) -> str | None:
        """Check if file has valid Python syntax. Returns error message or None."""
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                code = f.read()
            compile(code, str(file_path), 'exec')
            return None
        except SyntaxError as e:
            return f"Line {e.lineno}: {e.msg}"
        except Exception as e:
            return str(e)



