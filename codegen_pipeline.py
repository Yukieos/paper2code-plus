def strip_fences(block: str) -> str:
    """Remove markdown code fences and return the raw content."""
    cleaned = block.strip()

    if cleaned.startswith("```"):
        lines = cleaned.splitlines()
        if lines:
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
        cleaned = "\n".join(lines).strip()

    return cleaned


def validate_plan(plan_dict: Dict[str, Any]) -> CodePlan:
    """Validate and auto-fix plan structure using Pydantic."""
    try:
        return CodePlan(**plan_dict)
    except ValidationError as e:
        logger.warning(f"Plan validation errors: {e}")
        # Auto-fix common issues
        if 'files' in plan_dict:
            for file_spec in plan_dict['files']:
                if 'acceptance_criteria' not in file_spec or not file_spec['acceptance_criteria']:
                    file_spec['acceptance_criteria'] = ["File compiles without errors", "All functions implemented"]
                if 'function_skeletons' not in file_spec:
                    file_spec['function_skeletons'] = []
        
        # Retry validation
        return CodePlan(**plan_dict)


def enforce_standard_structure(plan_model: CodePlan) -> CodePlan:
    """
    Ensure that the generated plan conforms to a minimal standardized repository layout.

    - Always ensure there is a 'main.py' entrypoint.
    - Always ensure there is a 'config.json' configuration file.
    """
    existing_paths = {f.path for f in plan_model.files}
    files = list(plan_model.files)

    if "main.py" not in existing_paths:
        files.append(
            FileSpec(
                path="main.py",
                purpose="Main training and evaluation entrypoint for the reproduced experiments.",
                content_outline=[
                    "Parse command line arguments (including --config and --seed)",
                    "Load configuration from config.json",
                    "Set random seeds and initialize logging",
                    "Instantiate datasets, models, optimizer, and training loop",
                    "Run training and evaluation according to the UPS-IR specification",
                ],
                key_functions=["main", "train", "evaluate"],
                function_skeletons=[],
                dependencies=["argparse", "logging", "torch"],
                requires_parameters=[],
                acceptance_criteria=[
                    "Script can be run as `python main.py --config path/to/config.json --seed 0`",
                    "Training and evaluation complete without runtime errors",
                ],
            )
        )

    if "config.json" not in existing_paths:
        files.append(
            FileSpec(
                path="config.json",
                purpose="JSON configuration file for all experiment hyperparameters and paths.",
                content_outline=[
                    "Global training configuration section",
                    "Model architecture hyperparameters",
                    "Data paths and preprocessing options",
                    "Evaluation and logging configuration",
                ],
                key_functions=[],
                function_skeletons=[],
                dependencies=[],
                requires_parameters=[],
                acceptance_criteria=[
                    "Can be loaded as valid JSON without errors",
                    "Includes all required parameters referenced by the codebase",
                ],
            )
        )

    plan_model.files = files
    return plan_model


def summarize_ups_ir(ups_ir: Dict[str, Any], max_chars: int = 6000) -> str:
    serialized = json.dumps(ups_ir, ensure_ascii=False, indent=2)
    if len(serialized) <= max_chars:
        return serialized
    return serialized[: max_chars - 3] + "..."


@dataclass
class PlannerConfig:
    output_path: Path
    model_name: str = "gpt-4o-mini"
    temperature: float = 0.0

    def __post_init__(self) -> None:
        self.output_path = self.output_path.resolve()
        self.output_path.parent.mkdir(parents=True, exist_ok=True)


class PlannerAgent:
    def __init__(self, config: PlannerConfig):
        self.config = config
        # Use structured outputs so the model directly returns a CodePlan object.
        self.llm = ChatOpenAI(
            model=config.model_name,
            temperature=config.temperature,
        ).with_structured_output(CodePlan, method="function_calling")
        prompt = ChatPromptTemplate.from_template(PLAN_PROMPT)
        self.chain = prompt | self.llm

    def run(self, state: CodegenState) -> CodegenState:
        if "ups_ir" not in state:
            raise ValueError("PlannerAgent requires 'ups_ir' in state.")

        ups_ir_json = json.dumps(state["ups_ir"], ensure_ascii=False, indent=2)
        
        max_attempts = 3
        for attempt in range(max_attempts):
            try:
                # With structured outputs, this returns a CodePlan instance.
                plan_model: CodePlan = self.chain.invoke({"ups_ir_json": ups_ir_json})

                # Enforce standardized repository layout (main.py, config.json, etc.).
                plan_model = enforce_standard_structure(plan_model)
                plan = plan_model.model_dump()

                with open(self.config.output_path, "w", encoding="utf-8") as fp:
                    json.dump(plan, fp, ensure_ascii=False, indent=2)

                logger.info("PlannerAgent wrote plan to %s", self.config.output_path)
                state["plan"] = plan
                return state
            
            except (ValueError, ValidationError) as e:
                logger.warning(f"Plan generation attempt {attempt + 1} failed: {e}")
                if attempt < max_attempts - 1:
                    # Add error feedback to prompt for retry
                    ups_ir_json = f"Previous attempt failed with: {str(e)[:200]}\n\nPlease generate valid JSON.\n\n{ups_ir_json}"
                else:
                    # Final attempt failed - propagate error
                    logger.error("All plan generation attempts failed. Aborting.")
                    raise RuntimeError("Plan generation failed after multiple attempts.") from e
        
        return state


class PlanReviewerAgent:
    def __init__(self, config: PlannerConfig):
        self.config = config
        # Structured outputs for both critique and revised CodePlan.
        self.review_llm = ChatOpenAI(
            model=config.model_name,
            temperature=0.3,
        ).with_structured_output(PlanCritique, method="function_calling")
        self.review_prompt = ChatPromptTemplate.from_template(PLAN_REVIEW_PROMPT)
        self.review_chain = self.review_prompt | self.review_llm

        self.revise_llm = ChatOpenAI(
            model=config.model_name,
            temperature=0.2,
        ).with_structured_output(CodePlan, method="function_calling")
        self.revise_prompt = ChatPromptTemplate.from_template(PLAN_REVISE_PROMPT)
        self.revise_chain = self.revise_prompt | self.revise_llm

    def run(self, state: CodegenState) -> CodegenState:
        plan = state.get("plan")
        if not plan:
            raise ValueError("PlanReviewerAgent requires 'plan' in state.")
        
        ups_ir = state.get("ups_ir", {})
        
        # Generate critique with retry logic
        try:
            critique_model: PlanCritique = self.review_chain.invoke({
                "plan_json": json.dumps(plan, indent=2),
                "ups_ir_summary": summarize_ups_ir(ups_ir, max_chars=4000)
            })

            critique = critique_model.model_dump()
            state["plan_critique"] = json.dumps(critique, indent=2)
        except Exception as e:
            logger.warning(f"Critique generation failed: {e}. Using default critique.")
            critique = {
                "issues": ["Unable to generate detailed critique"],
                "improvements": ["Ensure all functions are fully implemented"]
            }
            state["plan_critique"] = json.dumps(critique, indent=2)
        
        # Generate revised plan based on critique with retry
        try:
            revised_plan_model: CodePlan = self.revise_chain.invoke({
                "original_plan": json.dumps(plan, indent=2),
                "critique": json.dumps(critique, indent=2)
            })

            # Ensure standardized structure for the revised plan.
            revised_plan_model = enforce_standard_structure(revised_plan_model)
            revised_plan = revised_plan_model.model_dump()
        except Exception as e:
            logger.warning(f"Plan revision failed: {e}. Using original plan with patches.")
            # Apply minimal fixes to original plan
            revised_plan = plan.copy()
            for file_spec in revised_plan.get("files", []):
                if not file_spec.get("acceptance_criteria"):
                    file_spec["acceptance_criteria"] = ["Implementation complete", "No syntax errors"]
        
        # Save revised plan
        revised_path = self.config.output_path.parent / "revised_code_plan.json"
        with open(revised_path, "w", encoding="utf-8") as fp:
            json.dump(revised_plan, fp, ensure_ascii=False, indent=2)
        
        logger.info("PlanReviewerAgent wrote revised plan to %s", revised_path)
        state["revised_plan"] = revised_plan
        state["plan"] = revised_plan  # Use revised plan going forward
        return state


