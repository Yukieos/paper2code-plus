    def _collect_dependencies(self, plan: Dict[str, Any], paper_type: str, state: CodegenState) -> Dict[str, str]:
        """Collect all dependencies from plan and generated code files."""
        dependencies = {}

        # Start with global dependencies from plan
        for dep in plan.get("global_dependencies", []):
            # Parse dependency string (e.g., "torch>=2.0.0" or just "torch")
            dep_name = dep.split(">")[0].split("<")[0].split("=")[0].split("!")[0].strip()
            if dep_name and dep_name not in dependencies:
                dependencies[dep_name] = dep

        # Add core libraries based on paper type
        core_deps = self._get_core_dependencies(paper_type)
        for name, spec in core_deps.items():
            if name not in dependencies:
                dependencies[name] = spec

        # Scan generated code files for import statements
        code_imports = self._scan_imports_from_files(state)
        for name, spec in code_imports.items():
            if name not in dependencies:
                dependencies[name] = spec

        # Map common import names to package names BEFORE returning
        # This ensures sklearn -> scikit-learn mapping happens
        import_to_package = {
            "sklearn": "scikit-learn",
            "cv2": "opencv-python",
            "PIL": "Pillow",
            "yaml": "PyYAML",
            "jwt": "PyJWT",
        }

        mapped_deps = {}
        for name, spec in dependencies.items():
            package_name = import_to_package.get(name, name)
            # Avoid duplicates - keep the one with version spec if both exist
            if package_name in mapped_deps and ">" not in spec and "<" not in spec:
                # Current spec has no version, keep the existing one
                continue
            mapped_deps[package_name] = spec

        return mapped_deps

    def _get_core_dependencies(self, paper_type: str) -> Dict[str, str]:
        """Get core dependencies based on paper type."""
        base_deps = {
            "numpy": "numpy>=1.21.0",
            "scipy": "scipy>=1.7.0",
            "scikit-learn": "scikit-learn>=1.0.0",
            "pandas": "pandas>=1.3.0",
            "matplotlib": "matplotlib>=3.4.0",
            "pytest": "pytest>=6.2.0",
        }

        if paper_type == PaperType.ML_TRAINING.value:
            base_deps.update({
                "torch": "torch>=2.0.0",
                "transformers": "transformers>=4.30.0",
                "tqdm": "tqdm>=4.60.0",
            })
        elif paper_type == PaperType.ALGORITHM.value:
            base_deps.update({
                "numba": "numba>=0.55.0",
            })

        return base_deps

    def _scan_imports_from_files(self, state: CodegenState) -> Dict[str, str]:
        """Scan all generated Python files for import statements."""
        imports = {}

        all_files = []
        all_files.extend(state.get("dataset_files", []))
        all_files.extend(state.get("execution_files", []))
        all_files.extend(state.get("evaluation_files", []))
        all_files.extend(state.get("generated_files", []))

        import re
        for file_path in all_files:
            path = Path(file_path)
            if not path.exists() or path.suffix != ".py":
                continue

            try:
                with open(path, "r", encoding="utf-8") as f:
                    code = f.read()

                # Find all import statements
                import_pattern = r'^(?:from|import)\s+([a-zA-Z0-9_\.]+)'
                matches = re.findall(import_pattern, code, re.MULTILINE)

                for match in matches:
                    # Get top-level package name
                    package = match.split(".")[0]
                    # Filter out standard library modules
                    stdlib_modules = {
                        "os", "sys", "re", "json", "logging", "pathlib", "typing", "argparse",
                        "dataclasses", "datetime", "enum", "tempfile", "collections", "itertools",
                        "functools", "operator", "time", "random", "math", "statistics", "decimal",
                        "abc", "io", "pickle", "hashlib", "hmac", "secrets", "struct", "codecs",
                        "unicodedata", "stringprep", "textwrap", "string", "difflib", "pprint",
                        "warnings", "contextlib", "threading", "multiprocessing", "subprocess",
                        "socket", "ssl", "email", "http", "urllib", "urllib2", "ftplib", "poplib",
                        "imaplib", "smtplib", "uuid", "socketserver", "xmlrpc", "ipaddress", "ast",
                        "symtable", "token", "keyword", "tokenize", "inspect", "importlib", "pkgutil"
                    }
                    if package not in stdlib_modules:
                        if package not in imports:
                            imports[package] = package
            except Exception as e:
                logger.warning(f"Error scanning imports from {path}: {e}")

        return imports

    def _generate_requirements(self, dependencies: Dict[str, str]) -> Path:
        """Generate requirements.txt file."""
        requirements_path = self.output_dir / "requirements.txt"

        # Sort dependencies alphabetically
        sorted_deps = sorted(dependencies.values())

        content = "# This file was auto-generated by the Paper2Code pipeline\n"
        content += "# Python dependencies for this project\n\n"
        content += "\n".join(sorted_deps)
        content += "\n"

        with open(requirements_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info(f"Generated requirements.txt with {len(dependencies)} dependencies")
        return requirements_path

    def _generate_environment_yml(self, dependencies: Dict[str, str], paper_type: str) -> Path:
        """Generate environment.yml file for conda."""
        environment_yml_path = self.output_dir / "environment.yml"

        # Extract package names and versions
        conda_deps = []
        pip_deps = []

        for dep_spec in sorted(dependencies.values()):
            # Some packages are better installed via conda
            if any(pkg in dep_spec for pkg in ["torch", "torchvision", "torchaudio", "cudatoolkit"]):
                conda_deps.append(f"  - {dep_spec}")
            elif any(pkg in dep_spec for pkg in ["pytorch", "tensorflow", "jax"]):
                conda_deps.append(f"  - {dep_spec}")
            else:
                pip_deps.append(dep_spec)

        # Build environment.yml content
        content = f"""# This file was auto-generated by the Paper2Code pipeline
        # Paper type: {paper_type}
        # To create this environment, run: conda env create -f environment.yml

        name: paper2code
        channels:
        - pytorch
        - conda-forge
        - defaults
        dependencies:
        - python=3.10
        - pip
        """

        if conda_deps:
            content += "\n".join(conda_deps) + "\n"

        if pip_deps:
            content += "  - pip:\n"
            for dep in pip_deps:
                content += f"    - {dep}\n"

        with open(environment_yml_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info(f"Generated environment.yml with conda and pip dependencies")
        return environment_yml_path


