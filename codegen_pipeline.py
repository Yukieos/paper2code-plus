class PaperTypeClassifier:
    """classifies paper type based on UPS-IR content to determine which agents to use."""

    def classify(self, ups_ir: Dict[str, Any]) -> PaperType:
        """
        Analyze UPS-IR content and determine paper type.

        Returns:
            PaperType enum indicating what kind of code generation pipeline to use
        """
        #check for training-related signals
        has_training_pipeline = bool(ups_ir.get("training_pipeline"))
        has_optimizations = bool(ups_ir.get("optimizations"))
        has_losses = bool(ups_ir.get("losses"))

        #check method names for training keywords
        methods = ups_ir.get("methods", [])
        has_training_methods = any(
            any(keyword in m.get("name", "").lower()
                for keyword in ["train", "optimize", "learn", "fit"])
            for m in methods
        )

        #check for dataset presence
        has_datasets = bool(ups_ir.get("datasets"))

        #check for experiments
        has_experiments = bool(ups_ir.get("experiments"))

        #check for algorithms
        algorithms = ups_ir.get("algorithms", [])
        has_algorithms = bool(algorithms)

        #check for equations (theoretical work)
        equations = ups_ir.get("equations", [])
        has_equations = bool(equations)

        #decision tree for classification
        if (has_training_pipeline or has_optimizations or has_losses or has_training_methods) and has_datasets:
            logger.info("Classified paper as ML_TRAINING: has training components and datasets")
            return PaperType.ML_TRAINING

        elif has_algorithms and not (has_training_pipeline or has_optimizations):
            logger.info("Classified paper as ALGORITHM: has algorithms but no training loop")
            return PaperType.ALGORITHM

        elif has_experiments and has_datasets and not (has_training_pipeline or has_optimizations):
            logger.info("Classified paper as ANALYSIS: has experiments and datasets but no training")
            return PaperType.ANALYSIS

        elif has_equations and not (has_algorithms or has_datasets or has_training_pipeline):
            logger.info("Classified paper as THEORETICAL: mainly equations, minimal computation")
            return PaperType.THEORETICAL

        else:
            #default to ML_TRAINING if unclear (conservative choice)
            logger.warning("Could not clearly classify paper type, defaulting to ML_TRAINING")
            return PaperType.ML_TRAINING

    def run(self, state: CodegenState) -> CodegenState:
        """Add paper_type to state."""
        if "ups_ir" not in state:
            raise ValueError("PaperTypeClassifier requires 'ups_ir' in state.")

        paper_type = self.classify(state["ups_ir"])
        state["paper_type"] = paper_type.value

        logger.info(f"Paper classified as: {paper_type.value}")
        return state


#pydantic models for validation
class ParameterSpec(BaseModel):
    name: str
    context: Optional[str] = None 
    defined_in_paper: bool = False
    value: Optional[str] = None
    suggested_values: str = ""
    reason: str = ""
    default_value: Optional[Any] = None
    risk_level: str = Field(default="low", pattern="^(low|medium|high)$")


class FunctionSkeleton(BaseModel):
    name: str
    signature: str
    docstring: str
    core_steps: List[str]
    key_variables: List[KeyVariable]
    dependencies: List[str] = []
    source_alignment: List[str] = []

class KeyVariable(BaseModel):
    name: str
    type: str
    purpose: str


class FlowStep(BaseModel):
    step_id: str
    description: str
    sequence_index: int
    source_reference: str
    figure_ids: List[str] = []
    algorithm_ids: List[str] = []
    equation_ids: List[str] = []
    prerequisites: List[str] = []
    consumes_variables: List[str] = []
    produces_variables: List[str] = []
    trigger_conditions: List[str] = []


class FlowTransition(BaseModel):
    from_step: str
    to_step: str
    condition: Optional[str] = None
    rationale: Optional[str] = None


class VariableDependency(BaseModel):
    variable: str
    depends_on: List[str]
    source_reference: str
    rationale: Optional[str] = None


class FlowReasoning(BaseModel):
    execution_order: List[FlowStep]
    transitions: List[FlowTransition] = []
    variable_dependencies: List[VariableDependency] = []


class FileSpec(BaseModel):
    path: str
    purpose: str
    content_outline: List[str]
    key_functions: List[str] = []
    function_skeletons: List[FunctionSkeleton] = []
    dependencies: List[str] = []
    requires_parameters: List[ParameterSpec] = []
    acceptance_criteria: List[str]
    
    @field_validator('acceptance_criteria')
    @classmethod
    def validate_acceptance_criteria(cls, v):
        if not v:
            raise ValueError("acceptance_criteria must not be empty")
        return v


class TestSpec(BaseModel):
    path: str
    purpose: str
    test_functions: List[str] = []


class CodePlan(BaseModel):
    repository_name: str
    summary: str
    global_dependencies: List[str] = []
    parameters: List[ParameterSpec] = []
    files: List[FileSpec]
    tests: List[TestSpec] = []
    flow_reasoning: Optional[FlowReasoning] = None
    
    @field_validator('files')
    @classmethod
    def validate_files(cls, v):
        if not v:
            raise ValueError("At least one file must be specified")
        return v


class PlanCritique(BaseModel):
    """Structured critique for a code generation plan."""

    issues: List[str] = Field(default_factory=list)
    improvements: List[str] = Field(default_factory=list)


class CodeReviewResult(BaseModel):
    """Structured result for code review of a single file."""

    issues: List[str] = Field(default_factory=list)
    # Parallel to issues; same length; each entry is a severity label for the corresponding issue.
    severity: List[str] = Field(default_factory=list)
    # Parallel to issues; suggested fix for each issue.
    suggestions: List[str] = Field(default_factory=list)


