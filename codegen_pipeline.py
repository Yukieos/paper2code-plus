class CodeReviewDebugAgent:
    """AI-driven code review and iterative debugging with fix loops."""

    @staticmethod
    def _detect_stub_functions(code: str) -> List[str]:
        """Functions/methods whose entire body is a no-op (`pass`, `...`, or
        a bare string) — syntactically fine, semantically empty. The LLM
        review doesn't reliably flag these on its own (a whole class of
        `pass`-only stub methods passed review in practice — see git
        history), so this is checked deterministically and force-merged
        into the review result rather than left to the model's judgment.
        """
        try:
            tree = ast.parse(code)
        except SyntaxError:
            return []

        stubs = []
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
                    and isinstance(body[0].value.value, str):
                body = body[1:]  # skip a leading docstring
            if not body:
                continue
            if all(isinstance(stmt, ast.Pass)
                   or (isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant))
                   for stmt in body):
                stubs.append(node.name)
        return stubs

    def __init__(self, model_name: str = "gpt-4o-mini", temperature: float = 0.0,
                 max_iterations: int = 3):
        self.model_name = model_name
        self.temperature = temperature
        self.max_iterations = max_iterations

        # Review LLM (strict, critical)
        self.review_llm = ChatOpenAI(
            model=model_name,
            temperature=0.1,
        )
        self.review_prompt = ChatPromptTemplate.from_template(CODE_REVIEW_PROMPT)
        self.review_chain = self.review_prompt | self.review_llm | StrOutputParser()

        # Fix LLM (focused on corrections)
        self.fix_llm = ChatOpenAI(
            model=model_name,
            temperature=0.2,
        )
        self.fix_prompt = ChatPromptTemplate.from_template(CODE_FIX_PROMPT)
        self.fix_chain = self.fix_prompt | self.fix_llm | StrOutputParser()

    def run(self, state: CodegenState) -> CodegenState:
        """Review code and apply fixes iteratively."""
        generated_files = state.get("generated_files", [])
        plan = state.get("plan", {})
        file_analysis = state.get("file_analysis", {})

        if not generated_files or not plan:
            logger.info("CodeReviewDebugAgent: No files to review or plan missing")
            return state

        reviews = {}
        fixed_count = 0

        # Create file spec map
        file_spec_map = {f.get("path"): f for f in plan.get("files", [])}

        for file_path in generated_files:
            path = Path(file_path)
            if not path.exists() or path.suffix != ".py":
                continue

            # generated_files holds absolute paths (output_dir / plan_path), but the
            # plan keys files by their relative path (e.g. "evaluation/evaluate.py").
            # Bare-filename/exact-string lookups only ever matched root-level files
            # (main.py, config.json) by accident — every nested file (data/, models/,
            # training/, evaluation/) silently skipped review. Match by relative-path
            # suffix instead.
            normalized_path = str(path).replace("\\", "/")
            file_spec = file_spec_map.get(path.name) or file_spec_map.get(str(path))
            if not file_spec:
                for spec_path, spec in file_spec_map.items():
                    if spec_path and normalized_path.endswith(spec_path.replace("\\", "/")):
                        file_spec = spec
                        break
            if not file_spec:
                logger.warning(f"No spec found for {path.name}, skipping review")
                continue

            # Get file analysis if available (from FileAnalysisAgent Stage 4.6)
            file_analysis_spec = file_analysis.get(path.name) or file_analysis.get(file_spec.get("path"))

            logger.info(f"CodeReviewDebugAgent reviewing {path.name}")

            # Iterative review and fix loop
            code = path.read_text(encoding="utf-8")
            iteration = 0
            passed = False

            while iteration < self.max_iterations and not passed:
                iteration += 1
                logger.info(f"  Iteration {iteration}/{self.max_iterations}")

                # Review code with file analysis
                review_result = self._review_code(code, file_spec, file_analysis_spec)

                stub_functions = self._detect_stub_functions(code)
                if stub_functions:
                    review_result["passed"] = False
                    review_result.setdefault("issues", [])
                    review_result["issues"].append(
                        f"These functions/methods have no real implementation (body is just a "
                        f"no-op): {', '.join(stub_functions)}. Implement real logic per the file "
                        f"spec — an empty stub is not acceptable even if it's syntactically valid."
                    )

                reviews[str(path)] = json.dumps(review_result, indent=2)

                if review_result.get("passed", False):
                    logger.info(f"  ✓ Code passed review on iteration {iteration}")
                    passed = True
                    # Write the reviewed/fixed code
                    path.write_text(code, encoding="utf-8")
                    fixed_count += 1
                elif iteration < self.max_iterations:
                    # Try to fix the code
                    issues_text = self._format_issues(review_result)
                    logger.info(f"  Found {len(review_result.get('issues', []))} issues, attempting fix...")

                    try:
                        fixed_code = self._fix_code(code, issues_text, file_spec, file_analysis_spec)
                        if fixed_code and len(fixed_code) > 50:
                            code = fixed_code
                        else:
                            logger.warning(f"  Fix attempt produced invalid code, keeping original")
                            break
                    except Exception as e:
                        logger.error(f"  Fix attempt failed: {e}")
                        break
                else:
                    logger.warning(f"  Max iterations reached, code still has issues")

            # Write final code
            if passed:
                path.write_text(code, encoding="utf-8")

        state["code_reviews"] = reviews
        logger.info(f"CodeReviewDebugAgent: Reviewed {len(generated_files)} files, "
                   f"fixed and passed {fixed_count}")

        return state

    def _review_code(self, code: str, file_spec: Dict[str, Any],
                     file_analysis_spec: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Review code using AI and file analysis specifications."""
        try:
            # Use file analysis if available, otherwise use empty object
            file_analysis_text = json.dumps(file_analysis_spec or {}, indent=2)

            review_text = self.review_chain.invoke({
                "code": code,
                "file_spec": json.dumps(file_spec, indent=2),
                "file_analysis": file_analysis_text,
                "acceptance_criteria": json.dumps(file_spec.get("acceptance_criteria", []))
            })

            # Parse review
            return self._parse_review(review_text)
        except Exception as e:
            logger.error(f"Review failed: {e}")
            return {"passed": False, "issues": [str(e)], "severity": ["high"]}

    def _fix_code(self, code: str, issues_text: str, file_spec: Dict[str, Any],
                  file_analysis_spec: Optional[Dict[str, Any]] = None) -> str:
        """Fix code based on review issues and file specifications."""
        try:
            # Use file analysis if available
            file_analysis_text = json.dumps(file_analysis_spec or {}, indent=2)

            fixed = self.fix_chain.invoke({
                "original_code": code,
                "issues": issues_text,
                "file_spec": json.dumps(file_spec, indent=2),
                "file_analysis": file_analysis_text,
            })

            return strip_fences(fixed)
        except Exception as e:
            logger.error(f"Fix attempt failed: {e}")
            return None

    @staticmethod
    def _format_issues(review_result: Dict[str, Any]) -> str:
        """Format review issues for the fix prompt."""
        issues = review_result.get("issues", [])
        severity = review_result.get("severity", [])
        suggestions = review_result.get("suggestions", [])

        formatted = "Issues found:\n"
        for i, issue in enumerate(issues):
            sev = severity[i] if i < len(severity) else "unknown"
            sugg = suggestions[i] if i < len(suggestions) else "N/A"
            formatted += f"{i+1}. [{sev}] {issue}\n   Fix: {sugg}\n"

        return formatted

    @staticmethod
    def _parse_review(review_text: str) -> Dict[str, Any]:
        """Parse AI review response."""
        try:
            import re
            json_match = re.search(r'\{.*\}', review_text, re.DOTALL)
            if json_match:
                return json.loads(json_match.group(0))
            else:
                # Heuristic: if "pass" or "ok" in text, consider it passed
                passed = any(word in review_text.lower() for word in ["pass", "ok", "good", "acceptable"])
                return {
                    "passed": passed,
                    "issues": [] if passed else ["Unable to parse detailed review"],
                    "severity": [] if passed else ["medium"],
                    "suggestions": [review_text],
                }
        except Exception as e:
            logger.warning(f"Failed to parse review: {e}")
            return {
                "passed": False,
                "issues": ["Review parsing failed"],
                "severity": ["high"],
                "suggestions": [str(e)],
            }


class EnvironmentGeneratorAgent:
    """Generates environment configuration files (requirements.txt, environment.yml) for reproducibility."""

