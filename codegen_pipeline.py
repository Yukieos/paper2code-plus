class PaperType(Enum):
    """Types of research papers based on their computational requirements."""
    ML_TRAINING = "ml_training"  #papers with training loops, optimizers, losses
    ALGORITHM = "algorithm"  #papers focused on algorithm implementation without training
    ANALYSIS = "analysis"  # data analysis, statistical experiments
    THEORETICAL = "theoretical"  # theoretical papers with equations but minimal code


