class MissingParameterReportAgent:
    def __init__(self, config: ParameterReportConfig):
        self.config = config

    def run(self, state: CodegenState) -> CodegenState:
        plan = state.get("plan")
        if not plan:
            raise ValueError("Missing plan in state; run planner first.")

        registry = self._collect_missing(plan)
        payload = {
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "parameters": sorted(registry.values(), key=lambda item: item["name"].lower()),
        }

        with open(self.config.output_path, "w", encoding="utf-8") as fp:
            json.dump(payload, fp, ensure_ascii=False, indent=2)

        logger.info(
            "MissingParameterReportAgent wrote %d entries to %s",
            len(payload["parameters"]),
            self.config.output_path,
        )
        state["missing_parameters"] = payload["parameters"]
        return state

    @staticmethod
    def _collect_missing(plan: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
        """Collect missing parameters with context-aware tracking to avoid collision."""
        registry: Dict[str, Dict[str, Any]] = {}

        # Track contexts for each parameter name
        param_contexts: Dict[str, List[Dict[str, Any]]] = {}

        def add_context(entry: Dict[str, Any], context: str = "global") -> None:
            """Add parameter with context to avoid name collisions."""
            name = entry.get("name")
            if not name:
                return
            
            # Create context-specific entry
            context_entry = {
                "context": context,
                    "reason": entry.get("reason", ""),
                "suggested_values": entry.get("suggested_values", ""),
                "default_value": entry.get("default_value"),
                "risk_level": entry.get("risk_level", "low"),
                "defined_in_paper": entry.get("defined_in_paper", False)
            }
            
            if name not in param_contexts:
                param_contexts[name] = []
            param_contexts[name].append(context_entry)

        # Collect global parameters
        for param in plan.get("parameters", []):
            if not param.get("defined_in_paper"):
                add_context(param, context="global")

        # Collect file-specific parameters
        for file_spec in plan.get("files", []):
            path = file_spec.get("path", "unknown")
            for requirement in file_spec.get("requires_parameters", []):
                if not requirement.get("defined_in_paper"):
                    add_context(requirement, context=path)

        # Build registry with context-aware keys
        for param_name, contexts in param_contexts.items():
            if len(contexts) == 1:
                # Single context - use simple name as key
                ctx = contexts[0]
                if not ctx["defined_in_paper"]:
                    registry[param_name] = {
                        "name": param_name,
                        "context": ctx["context"],
                        "reason": ctx["reason"],
                        "suggested_values": ctx["suggested_values"],
                        "default_value": ctx["default_value"],
                        "risk_level": ctx["risk_level"],
                        "referenced_files": [ctx["context"]] if ctx["context"] != "global" else [],
                    }
            else:
                # Multiple contexts - create separate entries with context suffix
                for ctx in contexts:
                    if not ctx["defined_in_paper"]:
                        # Use context-aware key to avoid collision
                        key = f"{param_name}@{ctx['context']}" if ctx['context'] != "global" else param_name
                        registry[key] = {
                            "name": param_name,
                            "context": ctx["context"],
                            "reason": ctx["reason"],
                            "suggested_values": ctx["suggested_values"],
                            "default_value": ctx["default_value"],
                            "risk_level": ctx["risk_level"],
                            "referenced_files": [ctx["context"]] if ctx["context"] != "global" else [],
                            "contexts_note": f"This parameter appears in multiple contexts: {', '.join(c['context'] for c in contexts)}"
                        }

        return registry


